// Writes src/lib/pdf/font-coverage.ts: the code points every embedded PDF
// face (src/lib/pdf/fonts/) can draw, as sorted [first, last] ranges. The
// form rejects user text outside them, because the renderer would otherwise
// draw an empty box for each such character. Rerun after changing the fonts:
//
//   npx tsx scripts/gen-font-coverage.ts
import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";
import { join } from "node:path";

interface FontkitFont {
  characterSet: number[];
}
const require = createRequire(import.meta.url);
// fontkit ships with @react-pdf/renderer and has no type declarations.
const fontkit = require("fontkit") as { openSync(path: string): FontkitFont };

const repoRoot = join(import.meta.dirname, "..");
const FACES = ["DejaVuSans.ttf", "DejaVuSans-Bold.ttf", "DejaVuSans-Oblique.ttf"];

const sets = FACES.map(
  (f) => new Set(fontkit.openSync(join(repoRoot, "src/lib/pdf/fonts", f)).characterSet),
);
const common = [...sets[0]]
  .filter((cp) => cp >= 0x20 && sets.every((s) => s.has(cp)))
  .sort((a, b) => a - b);

const ranges: [number, number][] = [];
for (const cp of common) {
  const last = ranges[ranges.length - 1];
  if (last && last[1] === cp - 1) last[1] = cp;
  else ranges.push([cp, cp]);
}

const body = ranges.map(([a, b]) => `  [0x${a.toString(16)}, 0x${b.toString(16)}],`).join("\n");
writeFileSync(
  join(repoRoot, "src/lib/pdf/font-coverage.ts"),
  `// Generated by scripts/gen-font-coverage.ts from src/lib/pdf/fonts/. Do not edit.
// Code points that every embedded PDF face can draw, as [first, last] ranges.
export const FONT_COVERAGE: readonly (readonly [number, number])[] = [
${body}
];
`,
);
console.log(`${ranges.length} ranges, ${common.length} code points`);
